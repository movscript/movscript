function assertIncludes(value: string, expected: string) {
  assert.equal(value.includes(expected), true, `expected output to include ${expected}`)
}

function assertNotIncludes(value: string, unexpected: string) {
  assert.equal(value.includes(unexpected), false, `expected output not to include ${unexpected}`)
}

function legacyAgentTerm(...parts: string[]) {
  return parts.join('')
}

function assertOrdered(value: string, expected: string[]) {
  let previousIndex = -1
  for (const item of expected) {
    const index = value.indexOf(item)
    assert.notEqual(index, -1, `expected output to include ${item}`)
    assert.ok(index > previousIndex, `expected ${item} to appear after the previous item`)
    previousIndex = index
  }
}
